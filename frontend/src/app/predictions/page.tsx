"use client";

import { useEffect, useState } from "react";

interface Sensor {
    id: number;
    sensor_code: string;
    location_name: string;
    location_type: string;
}

interface Prediction {
    sensor_code: string;
    location_name: string;
    location_type: string;
    forecast_time: string;
    predicted_people: number;
    crowd_level: string;
    model_name: string;
    model_version: string;
}

interface Evaluation {
    model_name: string;
    model_version: string;
    metrics: {
        mae: number;
        rmse: number;
        r2: number;
    };
    test_samples: number;
    sensors: number;
}

export default function PredictionsPage() {
    const [sensors, setSensors] = useState<Sensor[]>([]);
    const [selectedLocation, setSelectedLocation] = useState("");
    const [selectedSensorId, setSelectedSensorId] = useState<number | null>(
        null
    );

    const [availableDates, setAvailableDates] = useState<Set<string>>(
        new Set()
    );

    const [selectedDate, setSelectedDate] = useState("");
    const [calendarMonth, setCalendarMonth] = useState(new Date());

    const [predictions, setPredictions] = useState<Prediction[]>([]);
    const [evaluation, setEvaluation] = useState<Evaluation | null>(null);

    const [loading, setLoading] = useState(true);
    const [predictionLoading, setPredictionLoading] = useState(false);
    const [error, setError] = useState("");

    // =========================================================
    // LOAD PREDICTION LOCATIONS
    // =========================================================

    useEffect(() => {
        const fetchSensors = async () => {
            try {
                const response = await fetch(
                    "http://127.0.0.1:8000/api/predictions/sensors"
                );

                if (!response.ok) {
                    throw new Error("Failed to fetch prediction locations");
                }

                const result = await response.json();

                const sensorList: Sensor[] = result.sensors ?? [];

                setSensors(sensorList);

                if (sensorList.length > 0) {
                    setSelectedLocation(sensorList[0].location_name);
                    setSelectedSensorId(sensorList[0].id);
                }
            } catch (err) {
                console.error(err);
                setError("Failed to load prediction locations");
            } finally {
                setLoading(false);
            }
        };

        fetchSensors();
    }, []);
    useEffect(() => {
        const fetchEvaluation = async () => {
            try {
                const response = await fetch(
                    "http://127.0.0.1:8000/api/predictions/evaluation"
                );

                if (!response.ok) {
                    throw new Error("Failed to fetch evaluation metrics");
                }

                const result = await response.json();

                setEvaluation(result);
            } catch (err) {
                console.error(err);
            }
        };

        fetchEvaluation();
    }, []);

    // =========================================================
    // LOAD DATES GENERATED BY THE MODEL
    // =========================================================

    useEffect(() => {
        if (selectedSensorId === null) return;

        const fetchPredictionDates = async () => {
            try {
                setError("");
                setPredictions([]);

                const response = await fetch(
                    `http://127.0.0.1:8000/api/predictions/dates?sensor_id=${selectedSensorId}`
                );

                if (!response.ok) {
                    throw new Error("Failed to fetch prediction dates");
                }

                const result = await response.json();

                const dates: string[] = result.dates ?? [];

                setAvailableDates(new Set(dates));

                if (dates.length > 0) {
                    // Select latest date for which the model
                    // actually generated a forecast.
                    const latestDate = dates[dates.length - 1];

                    setSelectedDate(latestDate);

                    const latest = new Date(`${latestDate}T00:00:00`);

                    setCalendarMonth(
                        new Date(
                            latest.getFullYear(),
                            latest.getMonth(),
                            1
                        )
                    );
                } else {
                    setSelectedDate("");
                }
            } catch (err) {
                console.error(err);
                setAvailableDates(new Set());
                setSelectedDate("");
                setPredictions([]);
                setError("Failed to load prediction dates");
            }
        };

        fetchPredictionDates();
    }, [selectedSensorId]);

    // =========================================================
    // LOAD 24-HOUR MODEL FORECAST
    // =========================================================

    useEffect(() => {
        if (selectedSensorId === null || !selectedDate) return;

        const fetchForecast = async () => {
            setPredictionLoading(true);
            setError("");

            try {
                const response = await fetch(
                    `http://127.0.0.1:8000/api/predictions/forecast?sensor_id=${selectedSensorId}&forecast_date=${selectedDate}`
                );

                if (!response.ok) {
                    throw new Error("Failed to fetch prediction forecast");
                }

                const result = await response.json();

                setPredictions(result.predictions ?? []);
            } catch (err) {
                console.error(err);
                setPredictions([]);
                setError("Failed to load 24-hour crowd forecast");
            } finally {
                setPredictionLoading(false);
            }
        };

        fetchForecast();
    }, [selectedSensorId, selectedDate]);

    // =========================================================
    // LOCATION CHANGE
    // =========================================================

    const handleLocationChange = (locationName: string) => {
        const sensor = sensors.find(
            (item) => item.location_name === locationName
        );

        setSelectedLocation(locationName);
        setSelectedSensorId(sensor?.id ?? null);

        setSelectedDate("");
        setPredictions([]);
        setAvailableDates(new Set());
    };

    // =========================================================
    // CALENDAR
    // =========================================================

    const formatDate = (date: Date) => {
        const year = date.getFullYear();
        const month = String(date.getMonth() + 1).padStart(2, "0");
        const day = String(date.getDate()).padStart(2, "0");

        return `${year}-${month}-${day}`;
    };

    const year = calendarMonth.getFullYear();
    const month = calendarMonth.getMonth();

    const firstDay = new Date(year, month, 1).getDay();

    const daysInMonth = new Date(
        year,
        month + 1,
        0
    ).getDate();

    const calendarCells = [
        ...Array(firstDay).fill(null),
        ...Array.from(
            { length: daysInMonth },
            (_, index) => index + 1
        ),
    ];

    const isAvailableDate = (day: number) => {
        return availableDates.has(
            formatDate(new Date(year, month, day))
        );
    };

    const isSelectedDate = (day: number) => {
        return (
            selectedDate ===
            formatDate(new Date(year, month, day))
        );
    };

    const selectCalendarDate = (day: number) => {
        const date = new Date(year, month, day);

        const formatted = formatDate(date);

        if (!availableDates.has(formatted)) {
            return;
        }

        setSelectedDate(formatted);
    };

    // =========================================================
    // CROWD BADGE
    // =========================================================

    const getCrowdBadge = (level: string) => {
        switch (level) {
            case "Low":
                return "bg-green-500/15 text-green-400 border border-green-500/30";

            case "Moderate":
                return "bg-yellow-500/15 text-yellow-400 border border-yellow-500/30";

            case "High":
                return "bg-orange-500/15 text-orange-400 border border-orange-500/30";

            case "Very High":
                return "bg-red-500/15 text-red-400 border border-red-500/30";

            default:
                return "bg-gray-500/15 text-gray-400 border border-gray-500/30";
        }
    };

    // =========================================================
    // FORMAT HOURLY TIME
    // =========================================================

    const formatTime = (timestamp: string) => {
        const time = timestamp.split("T")[1].slice(0, 5);

        const [hour, minute] = time.split(":").map(Number);

        const nextHour = (hour + 1) % 24;

        const formatHour = (h: number) => {
            const period = h >= 12 ? "PM" : "AM";
            const displayHour = h % 12 || 12;

            return `${displayHour}:${minute
                .toString()
                .padStart(2, "0")} ${period}`;
        };

        return `${formatHour(hour)} - ${formatHour(nextHour)}`;
    };

    // =========================================================
    // GET MAX PREDICTION
    // =========================================================

    const getMaxPrediction = () => {
        if (predictions.length === 0) return 1;

        return Math.max(
            ...predictions.map(
                (prediction) => prediction.predicted_people
            )
        );
    };

    // =========================================================
    // LOADING
    // =========================================================

    if (loading) {
        return (
            <div className="min-h-screen bg-[#0b0f14] p-6 text-white">
                <h1 className="text-3xl font-bold">
                    Crowd Forecast
                </h1>

                <p className="mt-3 text-gray-500">
                    Loading prediction locations...
                </p>
            </div>
        );
    }

    // =========================================================
    // PAGE
    // =========================================================

    return (
        <div className="min-h-screen bg-[#0b0f14] p-6 text-white">
            <div className="mx-auto max-w-6xl">

                {/* HEADER */}
                <div className="mb-8">
                    <h1 className="text-3xl font-bold">
                        Crowd Forecast
                    </h1>

                    <p className="mt-2 text-gray-400">
                        24-hour crowd prediction generated by the ML model
                    </p>
                </div>

                {/* LOCATION */}
                <section className="mb-6 rounded-2xl border border-gray-800 bg-[#11161d] p-5 shadow-xl">
                    {/* MODEL EVALUATION */}
                    {evaluation && (
                        <section className="mb-6 rounded-2xl border border-gray-800 bg-[#11161d] p-5 shadow-xl">

                            <div className="mb-5">
                                <h2 className="text-xl font-semibold">
                                    Model Evaluation
                                </h2>

                                <p className="mt-1 text-sm text-gray-500">
                                    Performance of the crowd prediction model on the test dataset
                                </p>
                            </div>

                            <div className="grid grid-cols-2 gap-4 md:grid-cols-5">

                                <div className="rounded-xl border border-gray-800 bg-[#0b0f14] p-4">
                                    <p className="text-xs uppercase tracking-wider text-gray-500">
                                        MAE
                                    </p>
                                    <p className="mt-2 text-2xl font-bold text-white">
                                        {evaluation.metrics.mae.toFixed(2)}
                                    </p>
                                    <p className="mt-1 text-xs text-gray-600">
                                        people
                                    </p>
                                </div>

                                <div className="rounded-xl border border-gray-800 bg-[#0b0f14] p-4">
                                    <p className="text-xs uppercase tracking-wider text-gray-500">
                                        RMSE
                                    </p>
                                    <p className="mt-2 text-2xl font-bold text-white">
                                        {evaluation.metrics.rmse.toFixed(2)}
                                    </p>
                                    <p className="mt-1 text-xs text-gray-600">
                                        people
                                    </p>
                                </div>

                                <div className="rounded-xl border border-gray-800 bg-[#0b0f14] p-4">
                                    <p className="text-xs uppercase tracking-wider text-gray-500">
                                        R² Score
                                    </p>
                                    <p className="mt-2 text-2xl font-bold text-blue-400">
                                        {(evaluation.metrics.r2 * 100).toFixed(2)}%
                                    </p>
                                </div>

                                <div className="rounded-xl border border-gray-800 bg-[#0b0f14] p-4">
                                    <p className="text-xs uppercase tracking-wider text-gray-500">
                                        Test Samples
                                    </p>
                                    <p className="mt-2 text-2xl font-bold text-white">
                                        {evaluation.test_samples.toLocaleString()}
                                    </p>
                                </div>

                                <div className="rounded-xl border border-gray-800 bg-[#0b0f14] p-4">
                                    <p className="text-xs uppercase tracking-wider text-gray-500">
                                        Sensors
                                    </p>
                                    <p className="mt-2 text-2xl font-bold text-white">
                                        {evaluation.sensors}
                                    </p>
                                </div>

                            </div>

                            <p className="mt-4 text-xs text-gray-600">
                                Model: {evaluation.model_name} v{evaluation.model_version}
                            </p>

                        </section>
                    )}

                    <label className="mb-2 block text-xs font-semibold uppercase tracking-wider text-gray-500">
                        Location
                    </label>

                    <select
                        value={selectedLocation}
                        onChange={(event) =>
                            handleLocationChange(
                                event.target.value
                            )
                        }
                        className="w-full rounded-xl border border-gray-700 bg-[#0b0f14] px-4 py-3 text-white outline-none focus:border-blue-500"
                    >
                        {sensors.map((sensor) => (
                            <option
                                key={sensor.id}
                                value={sensor.location_name}
                                className="bg-[#0b0f14] text-white"
                            >
                                {sensor.location_name}
                            </option>
                        ))}
                    </select>

                </section>

                {/* CALENDAR */}
                <section className="mb-6 rounded-2xl border border-gray-800 bg-[#11161d] p-5 shadow-xl">

                    <div className="mb-5 flex items-center justify-between">

                        <div>
                            <h2 className="text-xl font-semibold">
                                Forecast Calendar
                            </h2>

                            <p className="mt-1 text-sm text-gray-500">
                                Select a date for which the model generated a forecast
                            </p>
                        </div>

                        <div className="flex gap-2">

                            <button
                                type="button"
                                onClick={() =>
                                    setCalendarMonth(
                                        new Date(
                                            year,
                                            month - 1,
                                            1
                                        )
                                    )
                                }
                                className="rounded-lg border border-gray-700 px-3 py-2 text-gray-300 hover:bg-[#172033]"
                            >
                                ←
                            </button>

                            <button
                                type="button"
                                onClick={() =>
                                    setCalendarMonth(
                                        new Date(
                                            year,
                                            month + 1,
                                            1
                                        )
                                    )
                                }
                                className="rounded-lg border border-gray-700 px-3 py-2 text-gray-300 hover:bg-[#172033]"
                            >
                                →
                            </button>

                        </div>

                    </div>

                    <div className="mb-4 text-center text-lg font-semibold">
                        {calendarMonth.toLocaleDateString(
                            "en-US",
                            {
                                month: "long",
                                year: "numeric",
                            }
                        )}
                    </div>

                    <div className="grid grid-cols-7 gap-2 text-center">

                        {[
                            "Sun",
                            "Mon",
                            "Tue",
                            "Wed",
                            "Thu",
                            "Fri",
                            "Sat",
                        ].map((day) => (
                            <div
                                key={day}
                                className="py-2 text-xs font-semibold uppercase text-gray-600"
                            >
                                {day}
                            </div>
                        ))}

                        {calendarCells.map(
                            (day, index) => {

                                if (day === null) {
                                    return (
                                        <div
                                            key={`empty-${index}`}
                                            className="min-h-[48px]"
                                        />
                                    );
                                }

                                const available =
                                    isAvailableDate(day);

                                const selected =
                                    isSelectedDate(day);

                                return (
                                    <button
                                        key={day}
                                        type="button"
                                        disabled={!available}
                                        onClick={() =>
                                            selectCalendarDate(
                                                day
                                            )
                                        }
                                        className={`min-h-[48px] rounded-lg border p-2 text-sm transition ${selected
                                            ? "border-blue-500 bg-blue-500/20 text-blue-400"
                                            : available
                                                ? "border-transparent text-gray-300 hover:border-gray-700 hover:bg-[#172033]"
                                                : "cursor-not-allowed border-transparent text-gray-700 opacity-40"
                                            }`}
                                    >
                                        {day}
                                    </button>
                                );
                            }
                        )}

                    </div>
                </section>

                {/* SELECTED DATE */}
                {selectedDate && (
                    <div className="mb-6 rounded-xl border border-gray-800 bg-[#11161d] px-5 py-4">

                        <p className="text-xs uppercase tracking-wider text-gray-600">
                            Forecast Date
                        </p>

                        <p className="mt-1 text-lg font-semibold">
                            {new Date(
                                `${selectedDate}T00:00:00`
                            ).toLocaleDateString(
                                "en-US",
                                {
                                    weekday: "long",
                                    year: "numeric",
                                    month: "long",
                                    day: "numeric",
                                }
                            )}
                        </p>

                    </div>
                )}

                {/* PREDICTION CHART */}
                {predictions.length > 0 && (
                    <section className="mb-6 rounded-2xl border border-gray-800 bg-[#11161d] p-5 shadow-xl">

                        <div className="mb-5">
                            <h2 className="text-xl font-semibold">
                                Predicted Crowd Trend
                            </h2>

                            <p className="mt-1 text-sm text-gray-500">
                                Expected number of people for the next 24 hours
                            </p>
                        </div>

                        <div className="overflow-x-auto">
                            <div className="flex min-w-[900px] items-end gap-3">

                                {predictions.map((prediction) => {
                                    const maxPrediction =
                                        getMaxPrediction();

                                    const height =
                                        (prediction.predicted_people /
                                            maxPrediction) *
                                        100;

                                    return (
                                        <div
                                            key={
                                                prediction.forecast_time
                                            }
                                            className="flex min-w-[34px] flex-1 flex-col items-center"
                                        >

                                            {/* VALUE */}
                                            <div className="mb-2 text-xs font-semibold text-gray-300">
                                                {Math.round(
                                                    prediction.predicted_people
                                                )}
                                            </div>

                                            {/* BAR */}
                                            <div className="flex h-56 w-full items-end justify-center rounded-lg bg-[#0b0f14]">

                                                <div
                                                    className="w-full max-w-[34px] rounded-t-md bg-blue-500 transition-all hover:bg-blue-400"
                                                    style={{
                                                        height: `${Math.max(
                                                            height,
                                                            3
                                                        )}%`,
                                                    }}
                                                    title={`${Math.round(
                                                        prediction.predicted_people
                                                    )} people`}
                                                />

                                            </div>

                                            {/* TIME */}
                                            <div className="mt-2 text-center text-[10px] text-gray-500">
                                                {
                                                    formatTime(
                                                        prediction.forecast_time
                                                    ).split(
                                                        " - "
                                                    )[0]
                                                }
                                            </div>

                                        </div>
                                    );
                                })}

                            </div>
                        </div>

                    </section>
                )}

                {/* 24-HOUR FORECAST */}
                <section className="overflow-hidden rounded-2xl border border-gray-800 bg-[#11161d] shadow-xl">

                    <div className="border-b border-gray-800 px-5 py-5 sm:px-6">

                        <h2 className="text-xl font-semibold">
                            24-Hour Crowd Forecast
                        </h2>

                        <p className="mt-1 text-sm text-gray-500">
                            Hourly crowd predictions generated by XGBoost
                        </p>

                    </div>

                    {predictionLoading ? (
                        <div className="px-6 py-14 text-center">
                            <p className="text-sm text-gray-500">
                                Loading 24-hour forecast...
                            </p>
                        </div>
                    ) : error ? (
                        <div className="px-6 py-14 text-center">
                            <p className="text-sm text-red-400">
                                {error}
                            </p>
                        </div>
                    ) : predictions.length === 0 ? (
                        <div className="px-6 py-14 text-center">
                            <p className="text-sm text-gray-500">
                                No model forecast is available for this date.
                            </p>
                        </div>
                    ) : (
                        <div className="overflow-x-auto">

                            <table className="w-full min-w-[600px]">

                                <thead>
                                    <tr className="border-b border-gray-800 bg-[#151b24] text-left">

                                        <th className="px-5 py-4 text-xs font-semibold uppercase tracking-wider text-gray-500">
                                            Time
                                        </th>

                                        <th className="px-5 py-4 text-xs font-semibold uppercase tracking-wider text-gray-500">
                                            Predicted People
                                        </th>

                                        <th className="px-5 py-4 text-xs font-semibold uppercase tracking-wider text-gray-500">
                                            Crowd Level
                                        </th>

                                    </tr>
                                </thead>

                                <tbody>

                                    {predictions.map(
                                        (prediction) => (
                                            <tr
                                                key={
                                                    prediction.forecast_time
                                                }
                                                className="border-b border-gray-800 last:border-0 hover:bg-[#151b24]"
                                            >

                                                <td className="px-5 py-4 text-sm text-gray-300">
                                                    {formatTime(
                                                        prediction.forecast_time
                                                    )}
                                                </td>

                                                <td className="px-5 py-4 text-sm font-semibold">
                                                    {Math.round(
                                                        prediction.predicted_people
                                                    )}{" "}
                                                    people
                                                </td>

                                                <td className="px-5 py-4">

                                                    <span
                                                        className={`inline-flex rounded-full px-2.5 py-1 text-xs font-semibold ${getCrowdBadge(
                                                            prediction.crowd_level
                                                        )}`}
                                                    >
                                                        {
                                                            prediction.crowd_level
                                                        }
                                                    </span>

                                                </td>

                                            </tr>
                                        )
                                    )}

                                </tbody>

                            </table>

                        </div>
                    )}

                </section>

            </div>
        </div>
    );
}